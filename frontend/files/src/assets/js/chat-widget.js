/**
 * Chat Widget JavaScript
 * A floating chat widget for customer support
 */

class ChatWidget {
  constructor(options = {}) {
    this.options = {
      title: 'Trợ lý Quân',
      subtitle: 'Xin chào tớ có thể giúp gì được cậu không',
      placeholder: 'Nhập tin nhắn...',
      apiUrl: options.apiUrl || 'https://aimarketingvn.com/webhook/chat',
      sessionExpireHours: options.sessionExpireHours || 24, // Session expires after 24 hours
      initialMessages: [
        {
          type: 'bot',
          text: 'Xin chào! Tôi có thể giúp gì cho bạn hôm nay?',
          time: new Date()
        }
      ],
      ...options
    };
    
    this.isOpen = false;
    this.messages = [...this.options.initialMessages];
    this.isTyping = false;
    
    // Initialize session ID with expiration handling
    this.initializeSession();

    this.init();
  }

  /**
   * Initialize or restore session ID from sessionStorage with expiration handling
   */
  initializeSession() {
    try {
      // Check for new format in sessionStorage first
      let sessionData = sessionStorage.getItem('chat_widget_session_data');
      
      // Migrate from localStorage if needed
      if (!sessionData) {
        const localSessionData = localStorage.getItem('chat_widget_session_data');
        const oldLocalSessionId = localStorage.getItem('chat_widget_session_id');
        
        if (localSessionData) {
          console.log('🔄 Chat Widget - Migrating session from localStorage to sessionStorage');
          sessionStorage.setItem('chat_widget_session_data', localSessionData);
          localStorage.removeItem('chat_widget_session_data'); // Clean up localStorage
          sessionData = localSessionData;
        } else if (oldLocalSessionId) {
          console.log('🔄 Chat Widget - Migrating session from old localStorage format');
          // Create new format with current timestamp (assume it's fresh)
          const migratedData = {
            sessionId: oldLocalSessionId,
            timestamp: new Date().getTime()
          };
          sessionStorage.setItem('chat_widget_session_data', JSON.stringify(migratedData));
          localStorage.removeItem('chat_widget_session_id'); // Clean up old format
          sessionData = JSON.stringify(migratedData);
        }
      }
      
      if (sessionData) {
        const { sessionId, timestamp } = JSON.parse(sessionData);
        const now = new Date().getTime();
        const expireTime = this.options.sessionExpireHours * 60 * 60 * 1000; // Convert hours to milliseconds
        
        // Check if session has expired
        if (now - timestamp < expireTime) {
          this.sessionId = sessionId;
          console.log('🔄 Chat Widget - Restored existing session from sessionStorage:', sessionId);
        } else {
          console.log('⏰ Chat Widget - Session expired, will create new session');
          this.clearSession();
        }
      } else {
        console.log('🆕 Chat Widget - No existing session found in sessionStorage');
      }
      
      // If no valid session, sessionId will be null and server will create new one
      if (!this.sessionId) {
        this.sessionId = null;
        console.log('🔧 Chat Widget - Session ID will be generated by server');
      }
    } catch (error) {
      console.error('❌ Chat Widget - Error initializing session:', error);
      this.clearSession();
    }
  }

  /**
   * Save session ID to sessionStorage with timestamp
   */
  saveSession(sessionId) {
    try {
      if (!sessionId) {
        console.warn('⚠️ Chat Widget - Attempted to save empty session ID');
        return;
      }
      
      const sessionData = {
        sessionId: sessionId,
        timestamp: new Date().getTime()
      };
      
      sessionStorage.setItem('chat_widget_session_data', JSON.stringify(sessionData));
      this.sessionId = sessionId;
      console.log('💾 Chat Widget - Session saved to sessionStorage:', sessionId);
    } catch (error) {
      console.error('❌ Chat Widget - Error saving session to sessionStorage:', error);
      // Fallback: try localStorage if sessionStorage fails
      try {
        localStorage.setItem('chat_widget_session_data', JSON.stringify(sessionData));
        this.sessionId = sessionId;
        console.log('💾 Chat Widget - Session saved to localStorage (fallback):', sessionId);
      } catch (fallbackError) {
        console.error('❌ Chat Widget - Both sessionStorage and localStorage failed:', fallbackError);
      }
    }
  }

  /**
   * Clear session data from both sessionStorage and localStorage
   */
  clearSession() {
    try {
      sessionStorage.removeItem('chat_widget_session_data');
      localStorage.removeItem('chat_widget_session_data');
      // Keep old key for backward compatibility cleanup
      localStorage.removeItem('chat_widget_session_id');
      this.sessionId = null;
      console.log('🗑️ Chat Widget - Session cleared from both storages');
    } catch (error) {
      console.error('❌ Chat Widget - Error clearing session:', error);
    }
  }

  init() {
    console.log('🚀 Chat Widget - Initializing...');
    
    // Test storage capabilities on init
    setTimeout(() => {
      this.checkStorageCapabilities();
    }, 500);
    
    this.createWidget();
    this.bindEvents();
    this.showNotificationBadge();
    
    // Debug visibility
    setTimeout(() => {
      const widgetRect = this.widget.getBoundingClientRect();
      const buttonRect = this.button.getBoundingClientRect();
      const computedStyle = window.getComputedStyle(this.widget);
      const buttonStyle = window.getComputedStyle(this.button);
      
      const isVisible = this.widget.offsetWidth > 0 && this.widget.offsetHeight > 0;
      const isInViewport = widgetRect.right > 0 && widgetRect.bottom > 0 && 
                          widgetRect.left < window.innerWidth && widgetRect.top < window.innerHeight;
      
      console.log('🔍 Chat Widget - Visibility Analysis:', {
        visible: isVisible,
        inViewport: isInViewport,
        widgetRect: widgetRect,
        buttonRect: buttonRect,
        zIndex: computedStyle.zIndex,
        buttonColor: buttonStyle.backgroundColor,
        pageBackground: window.getComputedStyle(document.body).backgroundColor
      });
      
      // Add debug class if query param exists
      if (window.location.search.includes('debug-chat')) {
        this.widget.classList.add('debug-mode');
        console.log('🚨 Chat Widget - DEBUG MODE ENABLED (red pulsing widget)');
      }
      
      if (!isVisible || !isInViewport) {
        console.warn('⚠️ Chat Widget - Widget may not be visible!');
        console.log('💡 Add ?debug-chat to URL to make widget super visible');
      }
    }, 1000);
  }

  createWidget() {
    console.log('🔧 Chat Widget - Creating widget DOM...');
    
    // Create chat widget container
    this.widget = document.createElement('div');
    this.widget.className = 'chat-widget';
    this.widget.innerHTML = this.getWidgetHTML();
    
    console.log('🔧 Chat Widget - Appending to body...');
    document.body.appendChild(this.widget);
    
    // Get references to elements
    this.button = this.widget.querySelector('.chat-widget-button');
    this.window = this.widget.querySelector('.chat-widget-window');
    this.messagesContainer = this.widget.querySelector('.chat-widget-messages');
    this.inputField = this.widget.querySelector('.chat-input-field');
    this.sendButton = this.widget.querySelector('.chat-send-button');
    this.badge = this.widget.querySelector('.chat-widget-badge');
    
    console.log('🔧 Chat Widget - Widget elements:', {
      button: this.button,
      window: this.window,
      widget: this.widget
    });
  }

  getWidgetHTML() {
    return `
      <button class="chat-widget-button" type="button">
        <i class="ti ti-message-circle"></i>
        <i class="ti ti-x"></i>
        <span class="chat-widget-badge">1</span>
      </button>
      
      <div class="chat-widget-window">
        <div class="chat-widget-header">
          <div class="chat-widget-avatar">
            <i class="ti ti-headset"></i>
          </div>
          <div class="chat-widget-info">
            <h6>${this.options.title}</h6>
            <p>${this.options.subtitle}</p>
          </div>
        </div>
        
        <div class="chat-widget-messages">
          ${this.renderMessages()}
        </div>
        
        <div class="chat-widget-input">
          <div class="chat-input-container">
            <input 
              type="text" 
              class="chat-input-field" 
              placeholder="${this.options.placeholder}"
              maxlength="500"
            >
            <button class="chat-send-button" type="button">
              <i class="ti ti-send"></i>
            </button>
          </div>
        </div>
      </div>
    `;
  }

  renderMessages() {
    return this.messages.map(message => this.renderMessage(message)).join('');
  }

  renderMessage(message) {
    const time = this.formatTime(message.time);
    const isUser = message.type === 'user';
    
    return `
      <div class="chat-message ${isUser ? 'user' : ''}">
        <div class="chat-message-avatar">
          <i class="ti ${isUser ? 'ti-user' : 'ti-robot'}"></i>
        </div>
        <div class="chat-message-content">
          <p class="chat-message-text">${this.escapeHtml(message.text)}</p>
          <div class="chat-message-time">${time}</div>
        </div>
      </div>
    `;
  }

  bindEvents() {
    // Toggle chat window
    this.button.addEventListener('click', () => {
      this.toggle();
    });

    // Send message on Enter key
    this.inputField.addEventListener('keypress', (e) => {
      if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        this.sendMessage();
      }
    });

    // Send message on button click
    this.sendButton.addEventListener('click', () => {
      this.sendMessage();
    });

    // Close widget on outside click
    document.addEventListener('click', (e) => {
      if (this.isOpen && !this.widget.contains(e.target)) {
        this.close();
      }
    });

    // Auto-resize input
    this.inputField.addEventListener('input', () => {
      this.updateSendButton();
    });
  }

  toggle() {
    if (this.isOpen) {
      this.close();
    } else {
      this.open();
    }
  }

  open() {
    this.isOpen = true;
    this.button.classList.add('active');
    this.window.classList.add('show');
    this.hideNotificationBadge();
    this.focusInput();
    this.scrollToBottom();
  }

  close() {
    this.isOpen = false;
    this.button.classList.remove('active');
    this.window.classList.remove('show');
  }

  async sendMessage() {
    const text = this.inputField.value.trim();
    if (!text) return;

    // Add user message
    this.addMessage({
      type: 'user',
      text: text,
      time: new Date()
    });

    // Clear input
    this.inputField.value = '';
    this.updateSendButton();

    // Show typing indicator
    this.showTyping();

    try {
      // Send to API
      const response = await this.sendToAPI(text);
      
      // Hide typing indicator
      this.hideTyping();
      
      // Add bot response
      this.addMessage({
        type: 'bot',
        text: response,
        time: new Date()
      });
    } catch (error) {
      console.error('❌ Chat Widget - Send message error:', error);
      this.hideTyping();
      
      let errorMessage = 'Xin lỗi, có lỗi xảy ra. Vui lòng thử lại sau.';
      
      // Handle specific error types
      if (error.message.includes('401') || error.message.includes('403')) {
        errorMessage = 'Phiên làm việc đã hết hạn. Tin nhắn tiếp theo sẽ tạo phiên mới.';
        console.log('🔄 Chat Widget - Session expired, next message will create new session');
      } else if (error.message.includes('network') || error.name === 'TypeError') {
        errorMessage = 'Lỗi kết nối mạng. Vui lòng kiểm tra internet và thử lại.';
      }
      
      this.addMessage({
        type: 'bot',
        text: errorMessage,
        time: new Date()
      });
    }
  }

  async sendToAPI(message) {
    // Log session status before sending
    console.log('📤 Chat Widget - Sending message with session ID:', this.sessionId);
    
    // Get auth token if available (check both storages)
    const token = sessionStorage.getItem('access_token') || localStorage.getItem('access_token');

    // Get current user metadata from auth.js functions
    let userData = {
      user_id: 0,
      user_name: 'Guest',
      user_email: 'guest@example.com',
      user_phone: '',
      user_address: '',
      user_city: '',
      user_state: '',
      user_zip: '',
      user_country: '',
      user_role: 'GUEST'
    };

    // Try to get actual user data if authenticated
    if (token && typeof getCurrentUser === 'function') {
      try {
        const currentUser = await getCurrentUser();
        if (currentUser) {
          userData = {
            user_id: currentUser.id || 0,
            user_name: currentUser.name || currentUser.username || 'User',
            user_email: currentUser.email || '',
            user_phone: currentUser.phone || '',
            user_address: currentUser.address || '',
            user_city: currentUser.city || '',
            user_state: currentUser.state || '',
            user_zip: currentUser.zip || '',
            user_country: currentUser.country || '',
            user_role: currentUser.role || 'USER'
          };
        }
      } catch (error) {
        console.warn('Failed to get user metadata:', error);
        // Continue with guest data if user fetch fails
      }
    }

    // Build ChatRequest payload with real user metadata
    const chatRequest = {
      ...userData,
      session_id: this.sessionId,
      message: message,
      timestamp: new Date().toISOString(),
      page_url: window.location.href,
      page_title: document.title
    };

    console.log('📤 Chat Widget - Request payload:', { 
      session_id: chatRequest.session_id, 
      message: chatRequest.message,
      user_name: chatRequest.user_name 
    });

    try {
      const response = await fetch(this.options.apiUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(token && { 'Authorization': `Bearer ${token}` })
        },
        body: JSON.stringify(chatRequest)
      });

      if (!response.ok) {
        // Handle session-related errors
        if (response.status === 401 || response.status === 403) {
          console.warn('🔒 Chat Widget - Authentication error, clearing session');
          this.clearSession();
        }
        throw new Error(`API request failed with status: ${response.status}`);
      }

      const data = await response.json();
      
      // Debug logging to see what we received
      console.log('📥 Chat Widget - API Response:', data);

      // Extract and handle session ID from various response formats
      const extractedSessionId = this.extractSessionId(data);
      if (extractedSessionId) {
        console.log('📥 Chat Widget - Session ID received:', extractedSessionId);
        this.saveSession(extractedSessionId);
      } else if (!this.sessionId) {
        console.warn('⚠️ Chat Widget - No session ID in response and no existing session');
      }

      // Extract message from various response formats
      return this.extractMessage(data);
      
    } catch (error) {
      console.error('❌ Chat Widget - API Error:', error);
      
      // Handle network errors that might indicate session issues
      if (error.name === 'TypeError' && error.message.includes('fetch')) {
        console.warn('🌐 Chat Widget - Network error, keeping current session');
      }
      
      throw error;
    }
  }

  /**
   * Extract session ID from various response formats
   */
  extractSessionId(data) {
    // Direct session_id in response
    if (data.session_id) {
      return data.session_id;
    }
    
    // Session ID in array response format: [{"session_id": "123", "output": "message"}]
    if (Array.isArray(data) && data.length > 0) {
      const firstItem = data[0];
      if (firstItem && firstItem.session_id) {
        return firstItem.session_id;
      }
    }
    
    // Session ID in nested data object
    if (data.data && data.data.session_id) {
      return data.data.session_id;
    }
    
    return null;
  }

  /**
   * Extract message content from various response formats
   */
  extractMessage(data) {
    // Handle array response format: [{"output": "message"}] from n8n API
    if (Array.isArray(data) && data.length > 0) {
      console.log('📥 Chat Widget - Array response detected, first item:', data[0]);
      const firstItem = data[0];
      
      if (firstItem && firstItem.output) {
        console.log('📥 Chat Widget - Returning output field:', firstItem.output);
        return firstItem.output;
      }
      
      // Fallback for other array formats
      if (firstItem && firstItem.out) {
        console.log('📥 Chat Widget - Returning out field:', firstItem.out);
        return firstItem.out;
      }
      
      // Direct message in array
      if (firstItem && firstItem.message) {
        console.log('📥 Chat Widget - Returning message field:', firstItem.message);
        return firstItem.message;
      }
      
      // If array item is a string
      if (typeof firstItem === 'string') {
        console.log('📥 Chat Widget - Returning string item:', firstItem);
        return firstItem;
      }
    }

    // Handle direct response formats for backward compatibility
    console.log('📥 Chat Widget - Using direct response handling');
    return data.response || data.message || data.output || data.text || 
           'Cảm ơn bạn đã liên hệ! Chúng tôi sẽ phản hồi sớm nhất có thể.';
  }

  addMessage(message) {
    this.messages.push(message);
    const messageElement = this.renderMessage(message);
    this.messagesContainer.insertAdjacentHTML('beforeend', messageElement);
    this.scrollToBottom();
  }

  showTyping() {
    if (this.isTyping) return;
    
    this.isTyping = true;
    const typingHTML = `
      <div class="chat-message typing-indicator">
        <div class="chat-message-avatar">
          <i class="ti ti-robot"></i>
        </div>
        <div class="chat-message-content">
          <div class="chat-typing">
            <div class="chat-typing-dot"></div>
            <div class="chat-typing-dot"></div>
            <div class="chat-typing-dot"></div>
          </div>
        </div>
      </div>
    `;
    this.messagesContainer.insertAdjacentHTML('beforeend', typingHTML);
    this.scrollToBottom();
  }

  hideTyping() {
    if (!this.isTyping) return;
    
    this.isTyping = false;
    const typingElement = this.messagesContainer.querySelector('.typing-indicator');
    if (typingElement) {
      typingElement.remove();
    }
  }

  showNotificationBadge() {
    setTimeout(() => {
      this.badge.classList.add('show');
    }, 2000);
  }

  hideNotificationBadge() {
    this.badge.classList.remove('show');
  }

  updateSendButton() {
    const hasText = this.inputField.value.trim().length > 0;
    this.sendButton.disabled = !hasText;
  }

  focusInput() {
    setTimeout(() => {
      this.inputField.focus();
    }, 300);
  }

  scrollToBottom() {
    setTimeout(() => {
      this.messagesContainer.scrollTop = this.messagesContainer.scrollHeight;
    }, 100);
  }

  formatTime(date) {
    return date.toLocaleTimeString('vi-VN', {
      hour: '2-digit',
      minute: '2-digit'
    });
  }

  escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
  }

  // Public methods
  addCustomMessage(text, type = 'bot') {
    this.addMessage({
      type: type,
      text: text,
      time: new Date()
    });
  }

  showBadge(count = '') {
    this.badge.textContent = count;
    this.badge.classList.add('show');
  }

  hideBadge() {
    this.badge.classList.remove('show');
  }

  // Session management methods
  getCurrentSessionId() {
    return this.sessionId;
  }

  resetSession() {
    console.log('🔄 Chat Widget - Manually resetting session');
    this.clearSession();
    this.addMessage({
      type: 'bot',
      text: 'Phiên chat đã được đặt lại. Tin nhắn tiếp theo sẽ bắt đầu cuộc trò chuyện mới.',
      time: new Date()
    });
  }

  getSessionInfo() {
    try {
      // Check sessionStorage first, then localStorage as fallback
      let sessionData = sessionStorage.getItem('chat_widget_session_data');
      let storageType = 'sessionStorage';
      
      if (!sessionData) {
        sessionData = localStorage.getItem('chat_widget_session_data');
        storageType = 'localStorage';
      }
      
      if (sessionData) {
        const { sessionId, timestamp } = JSON.parse(sessionData);
        const now = new Date().getTime();
        const ageMinutes = Math.floor((now - timestamp) / (1000 * 60));
        const expireMinutes = this.options.sessionExpireHours * 60;
        
        return {
          sessionId: sessionId,
          ageMinutes: ageMinutes,
          expiresInMinutes: expireMinutes - ageMinutes,
          isValid: ageMinutes < expireMinutes,
          storageType: storageType
        };
      }
      return { sessionId: null, isValid: false, storageType: 'none' };
    } catch (error) {
      console.error('❌ Chat Widget - Error getting session info:', error);
      return { sessionId: null, isValid: false, error: error.message, storageType: 'error' };
    }
  }
  
  // Debug helper methods
  makeSuperVisible() {
    this.widget.classList.add('debug-mode');
    console.log('🚨 Chat widget is now RED and PULSING for visibility testing');
  }
  
  makeNormal() {
    this.widget.classList.remove('debug-mode');
    console.log('✅ Chat widget back to normal appearance');
  }
  
  checkVisibility() {
    const rect = this.widget.getBoundingClientRect();
    const style = window.getComputedStyle(this.widget);
    const bodyStyle = window.getComputedStyle(document.body);
    
    console.table({
      'Widget Position': `${rect.right}px from left, ${rect.bottom}px from top`,
      'Widget Size': `${rect.width}x${rect.height}`,
      'Z-Index': style.zIndex,
      'Is Visible': rect.width > 0 && rect.height > 0,
      'In Viewport': rect.right > 0 && rect.left < window.innerWidth,
      'Page Background': bodyStyle.backgroundColor
    });
    
    return rect;
  }

  // Storage debugging helper
  checkStorageCapabilities() {
    const testKey = 'chat_widget_storage_test';
    const testValue = JSON.stringify({ test: true, timestamp: Date.now() });
    
    const result = {
      localStorage: { available: false, error: null },
      sessionStorage: { available: false, error: null }
    };

    // Test localStorage
    try {
      localStorage.setItem(testKey, testValue);
      const retrieved = localStorage.getItem(testKey);
      if (retrieved === testValue) {
        result.localStorage.available = true;
        localStorage.removeItem(testKey);
      }
    } catch (error) {
      result.localStorage.error = error.message;
    }

    // Test sessionStorage
    try {
      sessionStorage.setItem(testKey, testValue);
      const retrieved = sessionStorage.getItem(testKey);
      if (retrieved === testValue) {
        result.sessionStorage.available = true;
        sessionStorage.removeItem(testKey);
      }
    } catch (error) {
      result.sessionStorage.error = error.message;
    }

    console.log('💾 Chat Widget - Storage Capabilities:', result);
    console.table(result);
    
    return result;
  }
}

// Auto-initialize when DOM is ready
function autoInitChatWidget() {
  // Only initialize if not on login/register pages
  const currentPath = window.location.pathname;
  const isAuthPage = currentPath.includes('login') ||
                     currentPath.includes('register') ||
                     currentPath.includes('forgot-password') ||
                     currentPath.includes('reset-password') ||
                     currentPath.includes('code-verification') ||
                     currentPath.includes('landing.html') ||
                     currentPath.includes('error-') ||
                     currentPath.includes('coming-soon') ||
                     currentPath.includes('under-construction');

  console.log('🔍 Chat Widget - Current path:', currentPath);
  console.log('🔍 Chat Widget - Is auth page:', isAuthPage);

  if (!isAuthPage) {
    console.log('✅ Chat Widget - Initializing...');
    window.chatWidget = new ChatWidget({
      apiUrl: 'https://aimarketingvn.com/webhook/chat'
    });
    console.log('✅ Chat Widget - Widget created:', window.chatWidget);
  } else {
    console.log('❌ Chat Widget - Skipped (auth page)');
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', autoInitChatWidget);
} else {
  // DOM already loaded, initialize immediately
  autoInitChatWidget();
}

